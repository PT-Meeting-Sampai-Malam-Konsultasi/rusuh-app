/**
 * Known-answer tests. The reference matrices below were produced with the reference encoder
 * `qrcodegen` 1.8.0 (Project Nayuki) in byte mode, ECC level M, no ECC boost, mask chosen by lowest penalty.
 * Rows are written '#' = dark module and '.' = light module, no quiet zone. A one-off comparison of this
 * encoder against that reference over 320 payloads (every version 1..40, all four ECC levels, at and just
 * under each capacity) matched module for module.
 */
class QrMatrixTest {
    private fun QrMatrix.rows(): List<String> =
        (0 until size).map { y -> (0 until size).joinToString("") { x -> if (isDark(x, y)) "#" else "." } }

    @Test
    fun ticketPayloadMatchesReferenceMatrix() {
        val qr = QrMatrix.encode("RSH1.SMD-FB-04827.Q2hlY2tJbi1zaWduZWQ")
        assertEquals(3, qr.version)
        assertEquals(29, qr.size)
        assertEquals(QrEcc.Medium, qr.ecc)
        assertEquals(3, qr.mask)
        assertEquals(TICKET, qr.rows())
    }

    @Test
    fun shortPayloadMatchesReferenceMatrix() {
        val qr = QrMatrix.encode("HELLO")
        assertEquals(1, qr.version)
        assertEquals(4, qr.mask)
        assertEquals(HELLO, qr.rows())
    }

    @Test
    fun multiByteUtf8PayloadMatchesReferenceMatrix() {
        val qr = QrMatrix.encode("Caf\u00e9 \u2713 Rusuh!")
        assertEquals(2, qr.version)
        assertEquals(6, qr.mask)
        assertEquals(UTF8, qr.rows())
    }

    @Test
    fun version8WithVersionInfoMatchesReferenceMatrix() {
        val qr = QrMatrix.encode("RSH1.SMD-TA-11902.".repeat(7))
        assertEquals(8, qr.version)
        assertEquals(2, qr.mask)
        assertEquals(V8, qr.rows())
    }

    @Test
    fun version10WithTwoByteCharCountMatchesReferenceMatrix() {
        val qr = QrMatrix.encode("RSH1.SMD-FB-04827.".repeat(12).take(200))
        assertEquals(10, qr.version)
        assertEquals(3, qr.mask)
        assertEquals(V10, qr.rows())
    }

    @Test
    fun versionIsTheSmallestThatFitsAtLevelM() {
        val capacities = listOf(14, 26, 42, 62, 84, 106, 122, 152, 180, 213)
        capacities.forEachIndexed { index, capacity ->
            val version = index + 1
            assertEquals(capacity, QrMatrix.byteCapacity(version))
            assertEquals(version, QrMatrix.versionFor(capacity))
            assertEquals(version + 1, QrMatrix.versionFor(capacity + 1))
        }
    }

    @Test
    fun ticketPayloadLengthsFitInVersionThreeOrFour() {
        assertEquals(3, QrMatrix.versionFor("RSH1.SMD-FB-04827.Q2hlY2tJbi1zaWduZWQ".length))
        assertEquals(4, QrMatrix.versionFor(60))
    }

    @Test
    fun higherErrorCorrectionHoldsLessAndNeedsALargerVersion() {
        assertEquals(17, QrMatrix.byteCapacity(1, QrEcc.Low))
        assertEquals(14, QrMatrix.byteCapacity(1, QrEcc.Medium))
        assertEquals(11, QrMatrix.byteCapacity(1, QrEcc.Quartile))
        assertEquals(7, QrMatrix.byteCapacity(1, QrEcc.High))
        assertEquals(1, QrMatrix.versionFor(14, QrEcc.Medium))
        assertEquals(2, QrMatrix.versionFor(15, QrEcc.Medium))
        assertEquals(3, QrMatrix.versionFor(15, QrEcc.High))
        assertEquals(QrEcc.Quartile, QrMatrix.encode("abc", QrEcc.Quartile).ecc)
    }

    @Test
    fun maximumPayloadFitsInVersion40() {
        val max = QrMatrix.maxBytes()
        assertEquals(2331, max)
        val qr = QrMatrix.encode("a".repeat(max))
        assertEquals(40, qr.version)
        assertEquals(177, qr.size)
        assertNull(QrMatrix.versionFor(max + 1))
    }

    @Test
    fun tooLongPayloadIsRejected() {
        val failure =
            assertFailsWith<QrPayloadTooLongException> { QrMatrix.encode("a".repeat(QrMatrix.maxBytes() + 1)) }
        assertEquals(2332, failure.byteLength)
        assertEquals(2331, failure.maxBytes)
        assertFailsWith<QrPayloadTooLongException> { QrMatrix.encode("a".repeat(1274), QrEcc.High) }
    }

    @Test
    fun lengthIsMeasuredInUtf8BytesNotCharacters() {
        // 1166 two-byte characters are 2332 bytes: one too many.
        assertFailsWith<QrPayloadTooLongException> { QrMatrix.encode("\u00e9".repeat(1166)) }
        assertEquals(40, QrMatrix.encode("\u00e9".repeat(1165)).version)
    }

    @Test
    fun maskSelectionIsDeterministic() {
        val payload = "RSH1.SMD-FB-04828.Q2hlY2tJbi1zaWduZWQ"
        val first = QrMatrix.encode(payload)
        val second = QrMatrix.encode(payload)
        assertEquals(first.mask, second.mask)
        assertEquals(first.rows(), second.rows())
        assertTrue(first.mask in 0..7)
    }

    @Test
    fun differentPayloadsGiveDifferentMatrices() {
        val a = QrMatrix.encode("RSH1.SMD-FB-04827.Q2hlY2tJbi1zaWduZWQ")
        val b = QrMatrix.encode("RSH1.SMD-FB-04828.Q2hlY2tJbi1zaWduZWQ")
        assertNotEquals(a.rows(), b.rows())
    }

    @Test
    fun finderAndTimingPatternsArePlaced() {
        val qr = QrMatrix.encode("RSH1.SMD-FB-04827.Q2hlY2tJbi1zaWduZWQ")
        listOf(0 to 0, qr.size - 7 to 0, 0 to qr.size - 7).forEach { (ox, oy) ->
            for (i in 0..6) {
                assertTrue(qr.isDark(ox + i, oy) && qr.isDark(ox + i, oy + 6))
                assertTrue(qr.isDark(ox, oy + i) && qr.isDark(ox + 6, oy + i))
            }
            assertTrue(qr.isDark(ox + 3, oy + 3))
            assertFalse(qr.isDark(ox + 1, oy + 1))
        }
        for (i in 8 until qr.size - 8) assertEquals(i % 2 == 0, qr.isDark(i, 6))
        assertTrue(qr.isDark(8, qr.size - 8)) // the always-dark module
    }

    @Test
    fun modulesOutsideTheGridAreLight() {
        val qr = QrMatrix.encode("HELLO")
        assertFalse(qr.isDark(-1, 0))
        assertFalse(qr.isDark(0, qr.size))
    }
}

